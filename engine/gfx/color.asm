LoadMapPals:
	farcall LoadSpecialMapPalette
	jr c, .got_pals

	; Which palette group is based on whether we're outside or inside
	ld a, [wEnvironment]
	maskbits NUM_ENVIRONMENTS + 1
	ld e, a
	ld d, 0
	ld hl, EnvironmentColorsPointers
	add hl, de
	add hl, de
	ld a, [hli]
	ld h, [hl]
	ld l, a
	; Outdoor palettes carry a season axis; indoor, cave and dungeon do not,
	; which is what keeps winter out of Sprout Tower.
	ld a, [wEnvironment]
	cp TOWN
	jr z, .seasonal
	cp ROUTE
	jr nz, .no_season
.seasonal
	call GetPaletteSeason
	swap a
	add a ; season * 32, one season's block of four time-of-day rows
	ld e, a
	ld d, 0
	add hl, de
.no_season
	; Futher refine by time of day
	ld a, [wTimeOfDayPal]
	maskbits NUM_DAYTIMES
	add a
	add a
	add a
	ld e, a
	ld d, 0
	add hl, de
	ld e, l
	ld d, h
	ldh a, [rWBK]
	push af
	ld a, BANK(wBGPals1)
	ldh [rWBK], a
	ld hl, wBGPals1
	ld b, 8
.outer_loop
	ld a, [de] ; lookup index for TilesetBGPalette
	push de
	push hl
	ld l, a
	ld h, 0
	add hl, hl
	add hl, hl
	add hl, hl
	ld de, TilesetBGPalette
	add hl, de
	ld e, l
	ld d, h
	pop hl
	ld c, 1 palettes
.inner_loop
	ld a, [de]
	inc de
	ld [hli], a
	dec c
	jr nz, .inner_loop
	pop de
	inc de
	dec b
	jr nz, .outer_loop
	pop af
	ldh [rWBK], a

.got_pals
	ldh a, [rSVBK]
	push af
	ld a, BANK(wOBPals1)
	ldh [rSVBK], a
	ld hl, wOBPals1
	ld bc, 8 palettes
	ld a, $ff
	rst ByteFill
	ld hl, wOBPals2
	ld bc, 8 palettes
	ld a, $ff
	rst ByteFill
	pop af
	ldh [rSVBK], a
	farcall ClearSavedObjPals

	ld a, [wEnvironment]
	cp TOWN
	jr z, .outside
	cp ROUTE
	ret nz
.outside
; Roofs are seasonal. Only reached for TOWN and ROUTE, which is also why no
; darkness guard is needed -- no TOWN or ROUTE map sets IN_DARKNESS.
	; The Fast Ship is drawn on PAL_BG_ROOF; every harbour shows it alike.
	ld a, [wMapTileset]
	ld b, MAPGROUP_FAST_SHIP
	cp TILESET_PORT
	jr z, .got_roof_group
	; The park's fountain rim is its only ROOF tile: light blue.
	ld b, MAPGROUP_CERULEAN
	cp TILESET_PARK
	jr z, .got_roof_group
	ld a, [wMapGroup]
	ld b, a
.got_roof_group
	ld a, b
	add a
	add a
	ld e, a
	ld d, 0
	call GetPaletteSeason
	add a
	ld c, a
	ld b, 0
	ld hl, SeasonRoofPals
	add hl, bc
	ld a, [hli]
	ld h, [hl]
	ld l, a
	add hl, de
	add hl, de
	add hl, de
	ld a, [wTimeOfDayPal]
	maskbits NUM_DAYTIMES
	cp NITE_F
	ld de, 4
	jr z, .nite
	jr c, .morn_day
; eve
	add hl, de
.nite
	add hl, de
.morn_day
	ld de, wBGPals1 palette PAL_BG_ROOF color 1
	ld bc, 4
	ld a, BANK(wBGPals1)
	jmp FarCopyWRAM

GetPaletteSeason:
; The Orange Islands are tropical: always summer palettes.
	ld a, [wCurRegion]
	cp ORANGE_REGION
	ld a, SUMMER_F
	ret z
	ld a, [wSeason]
	maskbits NUM_SEASONS ; wSeason is poked by hand when testing
	ret

