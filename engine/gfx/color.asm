CheckShininess:
; Check if a mon is shiny by DVs at bc.
; Return carry if shiny.

	ld l, c
	ld h, b

; Attack
	ld a, [hl]
	cp 12 << 4
	jr c, .not_shiny

; Defense
	ld a, [hli]
	and %1111
	cp 12
	jr c, .not_shiny

; Speed
	ld a, [hl]
	cp 12 << 4
	jr c, .not_shiny

; Special
	ld a, [hl]
	and %1111
	cp 12
	jr c, .not_shiny

; shiny
	scf
	ret

.not_shiny
	and a
	ret

