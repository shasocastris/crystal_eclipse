GoldenrodGymWhitneyScript:
	faceplayer
	opentext
	readvar VAR_BADGES
	ifequal NUM_BADGES, WhitneyRematchScript
	checkevent EVENT_BEAT_WHITNEY
	iftrue .FightDone
	writetext WhitneyBeforeText
	waitbutton
	closetext
	winlosstext WhitneyShouldntBeSoSeriousText, WhitneyLossText
	loadtrainer WHITNEY, WHITNEY1
	startbattle
	reloadmapafterbattle
	setevent EVENT_BEAT_WHITNEY
	setevent EVENT_MADE_WHITNEY_CRY
	setscene SCENE_GOLDENRODGYM_WHITNEY_STOPS_CRYING
	setevent EVENT_BEAT_BEAUTY_VICTORIA
	setevent EVENT_BEAT_BEAUTY_SAMANTHA
	setevent EVENT_BEAT_LASS_CARRIE
	setevent EVENT_BEAT_LASS_BRIDGET
.FightDone:
	changeblock 2, 17, $03 ; door
	changeblock 3, 17, $03 ; door
	opentext
	checkevent EVENT_MADE_WHITNEY_CRY
	iffalse .StoppedCrying
	writetext WhitneyYouMeanieText
	waitbutton
	closetext
	end

.StoppedCrying:
	checkevent EVENT_GOT_TM45_ATTRACT
	iftrue .GotAttract
	checkflag ENGINE_PLAINBADGE
	iftrue .GotPlainBadge
	writetext WhitneyWhatDoYouWantText
	promptbutton
	waitsfx
	writetext PlayerReceivedPlainBadgeText
	playsound SFX_GET_BADGE
	waitsfx
	setflag ENGINE_PLAINBADGE
	readvar VAR_BADGES
.GotPlainBadge:
	writetext WhitneyPlainBadgeText
	promptbutton
	verbosegiveitem TM_ATTRACT
	iffalse .NoRoomForAttract
	setevent EVENT_GOT_TM45_ATTRACT
	writetext WhitneyAttractText
	waitbutton
	closetext
	end

.GotAttract:
	writetext WhitneyStrenghtSurfFlyText
	waitbutton
.NoRoomForAttract:
	closetext
	end

WhitneyRematchScript:
	checkevent EVENT_WHITNEY_REMATCH
	iftrue .RematchDone
	checkevent EVENT_HEALED_MOOMOO
	iffalse .WhitneyReject
	opentext
	writetext WhitneyRematchText
	waitbutton
	closetext
	winlosstext WhitneyRematchWinLossText, WhitneyLossText
	loadtrainer WHITNEY, WHITNEY2
	startbattle
	reloadmapafterbattle
.RematchDone
	opentext
	writetext BeatenWhitneyAgainText
	waitbutton
	closetext
	end

.WhitneyReject
	writetext WhitneyRejectText
	waitbutton
	closetext
	end

